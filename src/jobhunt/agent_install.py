"""Register a project-local entry skill for terminal-capable AI assistants."""
from __future__ import annotations

from pathlib import Path

PLATFORMS = {
    "claude": Path(".claude/skills/job-hunt-agent/SKILL.md"),
    "codex": Path(".agents/skills/job-hunt-agent/SKILL.md"),
    "gemini": Path(".gemini/skills/job-hunt-agent/SKILL.md"),
    "copilot": Path(".github/skills/job-hunt-agent/SKILL.md"),
}
MARKER = "<!-- Generated by jobhunt agent-install. -->"
HEADER = """---
name: job-hunt-agent
description: >-
  Execute local job-hunt-agent commands to find and rank jobs, review CVs,
  prepare applications and cover letters, track applications, plan learning,
  and practise interviews. Use for job-hunting requests in this checkout.
---
"""


def install(root: Path, platform: str, *, update: bool = False) -> list[tuple[Path, str]]:
    """Preflight destinations, then install without replacing unrelated skills."""
    if platform not in (*PLATFORMS, "all"):
        raise ValueError(f"Unknown platform: {platform}")
    rules = root / "AGENTS.md"
    skills = root / ".github" / "skills"
    if not rules.is_file() or not (skills / "job-search" / "SKILL.md").is_file():
        raise ValueError("Run agent-install from the job-hunt-agent repository root (the folder with AGENTS.md).")
    content = (
        HEADER + f"\n{MARKER}\n\n# Job-hunt agent\n\n"
        "Use this skill only in the job-hunt-agent checkout. Run commands from its\n"
        "root, never from this skill directory. Read the current AGENTS.md and the\n"
        "matching .github/skills/<skill>/SKILL.md before acting. If those files are\n"
        "missing, stop and ask the user to open the checkout; do not run elsewhere.\n\n"
        "The shared rules below are included so safety and execution requirements\n"
        "also apply when the host loads skills without repository instructions.\n\n"
        + rules.read_text(encoding="utf-8")
    )
    selected = PLATFORMS.values() if platform == "all" else [PLATFORMS[platform]]
    plan: list[tuple[Path, str]] = []
    for relative in selected:
        path = root / relative
        if any((root / part).is_symlink() for part in (relative, *relative.parents[:-1])):
            raise ValueError(f"Refusing symlink destination: {relative}; manage this skill manually.")
        if path.exists():
            if not path.is_file():
                raise ValueError(f"Skill destination is not a file: {relative}")
            previous = path.read_text(encoding="utf-8")
            if previous == content:
                plan.append((path, "unchanged"))
                continue
            if not previous.partition("\n---\n")[2].startswith(f"\n{MARKER}\n"):
                raise ValueError(f"Existing skill is not managed by jobhunt: {relative}; left untouched.")
            if not update:
                raise ValueError(f"Skill differs: {relative}; use --update to replace the generated skill.")
            plan.append((path, "updated"))
        else:
            plan.append((path, "installed"))
    for path, status in plan:
        if status != "unchanged":
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return plan
